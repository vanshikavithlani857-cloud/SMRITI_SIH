// Helper to recommend level based on recent answers history
export function calculateAdaptiveGameLevel(
  recentAnswers: { isCorrect: boolean }[]
): {
  recommendedLevel: GameDifficultyLevel;
  accuracy: number;
  totalAnswered: number;
  reason: string;
} {
  if (!recentAnswers || recentAnswers.length < 3) {
    return {
      recommendedLevel: 1,
      accuracy: 100,
      totalAnswered: recentAnswers ? recentAnswers.length : 0,
      reason: 'Welcome! Gentle Level 1 active to support ease, confidence, and cognitive comfort.',
    };
  }

  const sample = recentAnswers.slice(-6); // last 6 attempts
  const correctCount = sample.filter((a) => a.isCorrect).length;
  const accuracy = Math.round((correctCount / sample.length) * 100);

  if (accuracy >= 75) {
    return {
      recommendedLevel: 3,
      accuracy,
      totalAnswered: recentAnswers.length,
      reason: `Superb mental sharpness (${accuracy}% accuracy)! Level 3 active to stimulate memory and observation.`,
    };
  } else if (accuracy >= 50) {
    return {
      recommendedLevel: 2,
      accuracy,
      totalAnswered: recentAnswers.length,
      reason: `Consistent focus (${accuracy}% accuracy)! Level 2 active for steady visual recall and recognition.`,
    };
  } else {
    return {
      recommendedLevel: 1,
      accuracy,
      totalAnswered: recentAnswers.length,
      reason: `Gentle Level 1 active (${accuracy}% accuracy) to provide reassuring cues and warm encouragement without stress.`,
    };
  }
}
